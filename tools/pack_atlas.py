"""Pack individual sprite PNGs from Assets/ into a few atlas sheets (keeps the repo under GitHub's
100-files-per-web-upload limit). The game slices them back into separate images at load time.
Usage: python3 tools/pack_atlas.py <project_dir_with_individual_Assets> <output_project_dir>
Writes <out>/Assets/atlas/*.png and <out>/data/assets.js"""
import json, os, sys, shutil
from PIL import Image

SRC, OUT = sys.argv[1], sys.argv[2]
MAX = 2048          # keep each sheet <= 2048x2048 (safe for iPad memory)
PAD = 2
M = json.load(open(f'{SRC}/Assets/asset_manifest.json'))

# group -> which manifest entries go in it (used by the game now vs. future phases)
def group(m):
    f = m['file']
    if m['status'] == 'unassigned' or f.endswith('.jpg'): return None
    if m['status'] in ('assigned-phase2', 'assigned-phase3') or f.startswith('Assets/Traps'): return 'future'
    if m['id'].startswith('BOSS_') and m['id'] != 'BOSS_GIANT_ZOMBIE_KUMA': return 'future'
    if m['id'] in ('ZOM_MINER', 'ZOM_CHEF_MELEE', 'ZOM_GHOST'): return 'future'
    if f.startswith('Assets/UI') or f.startswith('Assets/Effects') or f.startswith('Assets/Donuts'): return 'ui'
    return 'units'

def pack(items, name):
    items = sorted(items, key=lambda it: -it[1].height)
    sheets, placed = [], []
    def new_sheet(): sheets.append({'x': 0, 'y': 0, 'row': 0, 'w': 0, 'h': 0, 'items': []})
    new_sheet()
    for mid, im in items:
        s = sheets[-1]
        if s['x'] + im.width + PAD > MAX: s['x'] = 0; s['y'] += s['row'] + PAD; s['row'] = 0
        if s['y'] + im.height + PAD > MAX: new_sheet(); s = sheets[-1]
        s['items'].append((mid, im, s['x'], s['y'])); s['row'] = max(s['row'], im.height)
        s['w'] = max(s['w'], s['x'] + im.width); s['h'] = max(s['h'], s['y'] + im.height); s['x'] += im.width + PAD
    out = {}
    for i, s in enumerate(sheets):
        sheet_name = f'{name}{i + 1}'
        canvas = Image.new('RGBA', (s['w'], s['h']), (0, 0, 0, 0))
        for mid, im, x, y in s['items']:
            canvas.paste(im, (x, y)); out[mid] = [sheet_name, x, y, im.width, im.height]
        canvas.save(f'{OUT}/Assets/atlas/{sheet_name}.png', optimize=True)
    return out, [f'{name}{i + 1}' for i in range(len(sheets))]

os.makedirs(f'{OUT}/Assets/atlas', exist_ok=True)
groups = {}
for m in M:
    g = group(m)
    if g: groups.setdefault(g, []).append((m['id'], Image.open(f"{SRC}/{m['file']}").convert('RGBA')))
atlas, sheets = {}, {}
for g, items in groups.items():
    a, names = pack(items, g); atlas.update(a)
    for n in names: sheets[n] = f'Assets/atlas/{n}.png'
files = {}
for m in M:
    if m['file'].endswith('.jpg') and m['status'] != 'unassigned':
        files[m['id']] = m['file']
        os.makedirs(os.path.dirname(f"{OUT}/{m['file']}"), exist_ok=True); shutil.copy(f"{SRC}/{m['file']}", f"{OUT}/{m['file']}")
with open(f'{OUT}/data/assets.js', 'w') as fh:
    fh.write('// Generated by tools/pack_atlas.py from Assets/asset_manifest.json — do not edit by hand\n')
    fh.write('// assetFiles: id -> standalone image file · atlas: id -> [sheet, x, y, w, h] · atlasSheets: sheet -> file\n')
    fh.write('RK.Data.assetFiles = ' + json.dumps(files, indent=1) + ';\n')
    fh.write('RK.Data.atlas = ' + json.dumps(atlas) + ';\n')
    fh.write('RK.Data.atlasSheets = ' + json.dumps(sheets, indent=1) + ';\n')
print('sheets:', {n: Image.open(f'{OUT}/{p}').size for n, p in sheets.items()}, 'sprites:', len(atlas), 'jpg:', len(files))
